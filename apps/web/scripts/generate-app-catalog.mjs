import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const composeDir = join(here, '..', '..', '..', 'internal', 'engine', 'compose');
const outFile = join(here, '..', 'src', 'features', 'templates', 'app-catalog.generated.ts');

export function parseScalar(line) {
  const match = line.match(/^  ([A-Za-z_]+):\s*(.*?)\s*$/);
  if (!match) return null;
  let value = match[2];
  if (
    (value.startsWith('"') && value.endsWith('"')) ||
    (value.startsWith("'") && value.endsWith("'"))
  ) {
    value = value.slice(1, -1);
  }
  if (value === 'true') return [match[1], true];
  if (value === 'false') return [match[1], false];
  return [match[1], value];
}

export function parseCatalogEntry(id, text) {
  const lines = text.split('\n');
  const meta = {};
  let services = [];
  let secrets = [];
  let mode = 'scan';
  let currentSecret = null;
  for (const line of lines) {
    if (/^\S/.test(line)) {
      if (line.startsWith('x-codedock:')) mode = 'meta';
      else if (line.startsWith('services:')) mode = 'services';
      else mode = 'scan';
      continue;
    }
    if (mode === 'secrets' && /^  [A-Za-z_]+:/.test(line) && !line.startsWith('  secrets:')) {
      mode = 'meta';
    }
    if (mode === 'meta') {
      if (/^  secrets:\s*$/.test(line)) {
        mode = 'secrets';
        continue;
      }
      const parsed = parseScalar(line);
      if (parsed) meta[parsed[0]] = parsed[1];
    } else if (mode === 'secrets') {
      const item = line.match(/^    - var:\s*(.*?)\s*$/);
      if (item) {
        currentSecret = { var: item[1], label: '', length: 0 };
        secrets.push(currentSecret);
        continue;
      }
      const label = line.match(/^      label:\s*(.*?)\s*$/);
      if (label && currentSecret) currentSecret.label = label[1];
      const length = line.match(/^      length:\s*(\d+)\s*$/);
      if (length && currentSecret) currentSecret.length = Number(length[1]);
    } else if (mode === 'services') {
      const service = line.match(/^  ([A-Za-z0-9_.-]+):\s*$/);
      if (service) services.push(service[1]);
    }
  }
  if (!meta.is_one_click) return null;
  return {
    id,
    name: meta.name || id,
    description: meta.description || '',
    category: meta.category || 'other',
    icon: meta.icon || id,
    verified: meta.verified === true,
    services,
    secrets,
  };
}

function emit(entries) {
  const body = JSON.stringify(entries, null, 2);
  return `// Generated by scripts/generate-app-catalog.mjs from internal/engine/compose/*.yaml — do not edit by hand.
export interface AppCatalogSecret {
  var: string;
  label: string;
  length: number;
}

export interface AppCatalogEntry {
  id: string;
  name: string;
  description: string;
  category: string;
  icon: string;
  verified: boolean;
  services: string[];
  secrets: AppCatalogSecret[];
}

export const appCatalog: AppCatalogEntry[] = ${body};
`;
}

const entries = [];
for (const file of readdirSync(composeDir).sort()) {
  if (!file.endsWith('.yaml')) continue;
  const entry = parseCatalogEntry(
    file.replace(/\.yaml$/, ''),
    readFileSync(join(composeDir, file), 'utf8')
  );
  if (entry) entries.push(entry);
}
entries.sort((a, b) => a.name.localeCompare(b.name));
writeFileSync(outFile, emit(entries));
console.log(`wrote ${entries.length} catalog entries to ${outFile}`);
